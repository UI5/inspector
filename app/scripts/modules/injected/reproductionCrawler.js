'use strict';

// Hard ceiling so a huge app cannot freeze the page or blow up the message payload.
// When the tree has more controls than this, the crawl stops descending and marks the
// snapshot as truncated.
var DEFAULT_MAX_CONTROLS = 2000;

/**
 * Flatten a framework URLParameters map (`{key: [values]}`) into `{key: 'a, b'}`.
 * @param {Object} urlParameters
 * @returns {Object}
 * @private
 */
function _flattenUrlParameters(urlParameters) {
    var result = {};
    if (!urlParameters) {
        return result;
    }
    Object.keys(urlParameters).forEach(function (key) {
        var value = urlParameters[key];
        result[key] = Array.isArray(value) ? value.join(', ') : value;
    });
    return result;
}

/**
 * Detect a sap.ui.comp.* smart control. Smart controls bridge OData and dynamically create their
 * own internal child controls; the crawler marks those children so the prompt builder can annotate
 * them as auto-generated (the replica's smart control recreates them).
 * @param {Object} control - Live UI5 control instance.
 * @returns {boolean}
 * @private
 */
function _isSmartControl(control) {
    if (!control || typeof control.getMetadata !== 'function') {
        return false;
    }
    return (control.getMetadata().getLibraryName() || '').indexOf('sap.ui.comp') === 0;
}

/**
 * A control creates internal controls whose IDs start with "<parent id>-<suffix>" where the dash
 * is NOT followed by another dash (the "--" pattern belongs to view/component scopes, not to
 * internal children). This helper detects that relationship.
 * @param {string} id
 * @param {string} ancestorId
 * @returns {boolean}
 * @private
 */
function _isDerivedId(id, ancestorId) {
    if (!ancestorId) {
        return false;
    }
    return id.length > ancestorId.length + 1 &&
        id.indexOf(ancestorId + '-') === 0 &&
        id.charAt(ancestorId.length + 1) !== '-';
}

/**
 * Return true when `id` was auto-generated by any smart ancestor.
 * @param {string} id
 * @param {Array<string>} smartAncestorIds
 * @returns {boolean}
 * @private
 */
function _isSmartGenerated(id, smartAncestorIds) {
    for (var i = 0; i < smartAncestorIds.length; i++) {
        if (_isDerivedId(id, smartAncestorIds[i])) {
            return true;
        }
    }
    return false;
}

/**
 * Collect the non-default properties of a control, merging own and inherited metadata groups.
 * Own definitions win over inherited ones with the same name.
 * @param {Object} toolsAPI
 * @param {string} controlId
 * @returns {Array<{name: string, value: *, type: string}>}
 * @private
 */
function _collectProperties(toolsAPI, controlId) {
    var collected = [];
    var seen = Object.create(null);
    var data;

    try {
        data = toolsAPI.getControlProperties(controlId);
    } catch (e) {
        return collected;
    }

    if (!data) {
        return collected;
    }

    function addGroup(group) {
        if (!group || !group.properties) {
            return;
        }
        Object.keys(group.properties).forEach(function (name) {
            if (seen[name]) {
                return;
            }
            var property = group.properties[name];
            // Only non-default values matter for a reproduction — defaults are implied.
            if (property && property.isDefault === false) {
                seen[name] = true;
                collected.push({
                    name: name,
                    value: property.value,
                    type: property.type || ''
                });
            }
        });
    }

    addGroup(data.own);
    if (Array.isArray(data.inherited)) {
        data.inherited.forEach(addGroup);
    }

    return collected;
}

/**
 * Collect the binding information of a control: property bindings (path, model, mode) and
 * aggregation bindings (model only — ToolsAPI does not expose the aggregation path).
 * @param {Object} toolsAPI
 * @param {string} controlId
 * @returns {{properties: Object, aggregations: Object}}
 * @private
 */
function _collectBindings(toolsAPI, controlId) {
    var result = { properties: {}, aggregations: {} };
    var data;

    try {
        data = toolsAPI.getControlBindings(controlId);
    } catch (e) {
        return result;
    }

    if (!data) {
        return result;
    }

    if (data.properties) {
        Object.keys(data.properties).forEach(function (key) {
            var binding = data.properties[key];
            result.properties[key] = {
                path: binding.path || '',
                model: binding.model || '',
                mode: binding.mode || '',
                value: binding.value
            };
        });
    }

    if (data.aggregations) {
        Object.keys(data.aggregations).forEach(function (key) {
            result.aggregations[key] = {
                model: (data.aggregations[key] && data.aggregations[key].model) || ''
            };
        });
    }

    return result;
}

/**
 * Enrich one control node with aggregation name and smart-generated flag, using the live control
 * instance returned by the walk context's `getElement` function.
 * @param {Object} node - Raw DOM tree node.
 * @param {Object} walkCtx - `{getElement, smartAncestorIds}`.
 * @returns {{aggregation: string|undefined, isSmartGenerated: boolean}}
 * @private
 */
function _enrichFromLiveControl(node, walkCtx) {
    var liveControl = null;
    // getElement reaches into the live UI5 instance; a hostile/legacy app can make this throw. A
    // throw here must not abort the whole crawl, so swallow it and fall back to no enrichment.
    try {
        liveControl = walkCtx.getElement ? walkCtx.getElement(node.id) : null;
    } catch (e) {
        liveControl = null;
    }
    if (!liveControl) {
        return { aggregation: undefined, isSmartGenerated: false };
    }
    return {
        aggregation: liveControl.sParentAggregationName || undefined,
        isSmartGenerated: _isSmartGenerated(node.id, walkCtx.smartAncestorIds),
        isSmartControl: _isSmartControl(liveControl)
    };
}

/**
 * Walk the rendered control-tree model depth-first, enriching each control node with its
 * non-default properties, bindings, parent-aggregation name, and smart-generated flag. Follows
 * the DOM structure so the output matches what the UI5 Inspector shows.
 *
 * @param {Object} toolsAPI
 * @param {Array} nodes - ToolsAPI.getRenderedControlTree() output (or a `content` sub-array).
 * @param {{count: number, max: number, truncated: boolean}} state
 * @param {{getElement: Function|null, smartAncestorIds: Array<string>}} walkCtx
 * @returns {Array}
 * @private
 */
function _walk(toolsAPI, nodes, state, walkCtx) {
    var out = [];

    if (!Array.isArray(nodes)) {
        return out;
    }

    for (var i = 0; i < nodes.length; i++) {
        var node = nodes[i];

        if (state.count >= state.max) {
            state.truncated = true;
            break;
        }

        // Non-control grouping nodes (UIAreas) carry no inspectable data; keep their
        // structure and recurse into their content.
        var isControl = node.type === 'sap-ui-control';
        var liveInfo = isControl ? _enrichFromLiveControl(node, walkCtx) : {};

        var enriched = {
            id: node.id,
            type: node.name || '',
            isControl: isControl,
            properties: isControl ? _collectProperties(toolsAPI, node.id) : [],
            bindings: isControl ? _collectBindings(toolsAPI, node.id) : { properties: {}, aggregations: {} },
            aggregation: liveInfo.aggregation,
            isSmartGenerated: liveInfo.isSmartGenerated || undefined,
            children: []
        };

        if (isControl) {
            state.count += 1;
        }

        // Extend smart-ancestor tracking for children when this control is a smart control.
        var childSmartIds = walkCtx.smartAncestorIds;
        if (liveInfo.isSmartControl) {
            childSmartIds = walkCtx.smartAncestorIds.concat([node.id]);
        }

        var childCtx = { getElement: walkCtx.getElement, smartAncestorIds: childSmartIds };
        enriched.children = _walk(toolsAPI, node.content, state, childCtx);
        out.push(enriched);
    }

    return out;
}

/**
 * Build the application metadata block from framework information and page env.
 * @param {Object} frameworkInformation
 * @param {Object} env
 * @returns {Object}
 * @private
 */
function _buildMeta(frameworkInformation, env) {
    var info = frameworkInformation || {};
    var common = info.commonInformation || {};
    var computed = info.configurationComputed || {};

    return {
        framework: common.frameworkName || '',
        version: common.version || '',
        url: env.href || '',
        title: env.title || '',
        theme: computed.theme || '',
        locale: computed.language || computed.locale || '',
        libraries: info.loadedLibraries ? Object.keys(info.loadedLibraries) : [],
        bootstrap: info.configurationBootstrap || {},
        urlParameters: _flattenUrlParameters(info.URLParameters)
    };
}

/**
 * Crawl the inspected UI5 application into a serializable snapshot the ReproductionPromptBuilder
 * turns into an LLM prompt. Follows the same DOM tree the UI5 Inspector shows, enriched with
 * non-default properties, bindings, parent-aggregation names, and smart-control markers.
 *
 * @param {Object} toolsAPI - The page `ToolsAPI`. Needs `getRenderedControlTree`,
 *     `getFrameworkInformation`, `getControlProperties`, `getControlBindings`.
 * @param {Object} [env] - Page environment facts.
 * @param {string} [env.href] - `location.href` of the inspected page.
 * @param {string} [env.title] - `document.title` of the inspected page.
 * @param {Array} [env.consoleErrors] - Recent console-error snapshot from the error buffer.
 * @param {Function} [env.getElement] - Optional. Called with a control id; returns the live UI5
 *     control instance. When provided, enables aggregation-name annotation and smart-control
 *     detection that match what the UI5 Inspector shows.
 * @param {Object} [options]
 * @param {number} [options.maxControls] - Descent ceiling. Defaults to {@link DEFAULT_MAX_CONTROLS}.
 * @returns {Promise<Object>} Resolves with `{meta, consoleErrors, tree, stats}`.
 */
function crawl(toolsAPI, env, options) {
    env = env || {};
    options = options || {};

    // The whole synchronous body is wrapped so crawl() ALWAYS returns a promise and never throws
    // synchronously. The injected message dispatcher calls this handler without a try/catch, so a
    // synchronous throw here would mean no response is ever sent back and the panel hangs forever
    // in the "Crawling…" state.
    try {
        var state = {
            count: 0,
            max: typeof options.maxControls === 'number' ? options.maxControls : DEFAULT_MAX_CONTROLS,
            truncated: false
        };

        var getElement = typeof env.getElement === 'function' ? env.getElement : null;

        var treeModel;
        try {
            treeModel = toolsAPI.getRenderedControlTree();
        } catch (e) {
            treeModel = [];
        }

        var walkCtx = { getElement: getElement, smartAncestorIds: [] };
        var tree = _walk(toolsAPI, treeModel, state, walkCtx);

        var frameworkInformation;
        try {
            frameworkInformation = toolsAPI.getFrameworkInformation();
        } catch (e) {
            frameworkInformation = {};
        }

        return Promise.resolve(frameworkInformation).then(function (info) {
            return {
                meta: _buildMeta(info, env),
                consoleErrors: Array.isArray(env.consoleErrors) ? env.consoleErrors : [],
                tree: tree,
                stats: {
                    controlCount: state.count,
                    truncated: state.truncated
                }
            };
        });
    } catch (e) {
        return Promise.reject(e instanceof Error ? e : new Error(String(e)));
    }
}

module.exports = {
    DEFAULT_MAX_CONTROLS: DEFAULT_MAX_CONTROLS,
    _isSmartControl: _isSmartControl,
    _isDerivedId: _isDerivedId,
    crawl: crawl
};
